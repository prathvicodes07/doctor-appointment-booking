create table if not exists public.appointments (
  id bigint generated by default as identity primary key,
  name text not null,
  doctor text not null,
  date date not null,
  time text not null
);

alter table public.appointments enable row level security;

drop policy if exists "Anyone can view appointments" on public.appointments;
drop policy if exists "Anyone can create appointments" on public.appointments;

create policy "Anyone can view appointments"
on public.appointments
for select
to anon, authenticated
using (true);

create policy "Anyone can create appointments"
on public.appointments
for insert
to anon, authenticated
with check (true);

grant select, insert on public.appointments to anon, authenticated;
grant usage, select on sequence public.appointments_id_seq to anon, authenticated;
